## 7. 账户注销（软删除机制）

### 7.1 注销方式

您可随时通过 Herald 提供的自助入口申请注销账户。注销一经确认即不可撤销，请您审慎操作。

### 7.2 软删除机制

为兼顾您的"被遗忘权"与平台合规、审计及多租户数据完整性需求，Herald 的账户注销采用**软删除（Soft Delete）**机制，具体处理如下：

1. **账户进入注销态**：注销后，您的账户将进入"已注销"状态，**不可再用于登录**，亦不再对外可见为活动用户；
2. **个人信息匿名化**：您的个人身份信息（包括但不限于邮箱、昵称、密码哈希等）将被匿名化或不可逆地脱敏处理，**不再能够识别到您本人**；
3. **会话立即失效**：您所有现存登录会话将被立即终止、强制登出；
4. **OAuth 绑定解绑**：您账号绑定的第三方 OAuth（Google / GitHub / Facebook / Apple 等）将一并解绑；
