### 5.3 订阅计费规则

5.3.1 **首次订阅**：完成支付后，相应权益（含积分等）按您所在 Realm 的策略发放。

5.3.2 **自动续费**：自动续费由支付平台处理。您可在支付平台侧管理您的支付方式与续费设置。若续费支付失败，订阅可能进入"逾期（Past Due）"状态并暂停相应权益；多次失败后可能转为过期。

5.3.3 **升级 / 降级**：

- 升级一般采用按比例计费（Proration），即时生效；
- 降级一般在下一个计费周期生效，当前周期保持原权益；
- 具体规则以购买时的页面提示为准。

5.3.4 **取消订阅**：取消一般在当前计费周期结束时生效，您可在周期结束前继续使用相应权益。取消后数据保留期限由相应第三方应用或 Realm 规则决定。

### 5.4 一次性购买规则

5.4.1 一次性购买（如积分包）在支付成功后即时发放相应权益（如充值积分），**不创建订阅记录**，亦不自动续费。

5.4.2 一次性购买所发放积分的有效期以产品页面展示及您所在 Realm 的策略为准。

### 5.5 价格变更

我们或您所在 Realm 的管理员保留调整价格的权利。价格调整不影响已生效的订阅（除非法律另有规定或您另有书面约定），但将影响后续续费或新购买。

### 5.6 税费

除另有说明外，所示价格是否含税以购买页面及适用法律为准。涉及 MoR 模式时，相关税费由相应支付平台代收代缴。

### 5.7 发票

5.7.1 您可依据您所在 Realm 配置的发票政策，为已完成的付款申请发票。发票的开具主体、内容与流程以您所在 Realm 的销售方配置及发票政策为准。

