## 5. 费用与付款（订阅计费与一次性购买）

### 5.1 费用的产生

5.1.1 Herald 服务可能包含免费与付费部分。具体可购买的产品、价格、计费周期、积分策略等由您所在 Realm 配置决定，并在购买页面明示。您应在购买前仔细确认价格与条款。

5.1.2 付费服务主要分为两类：

- **订阅（Recurring）**：按固定周期（如月、年）自动计费与续费的持续性权益；
- **一次性购买（One-time）**：单次付款获取的权益（如一次性积分包），不形成持续订阅。

### 5.2 支付方式

5.2.1 所有付款均通过运营方接入的第三方支付平台（如 Stripe、Creem 等）处理。我们不在本地存储您的完整支付卡号或银行账户敏感信息。

5.2.2 您在支付平台完成支付后，支付平台会通过回调通知 Herald，系统据此开通相应权益。如遇支付延迟或失败，请优先联系所使用的支付平台。

