-- ====================================
-- Account deletion: original email hash lookup
-- ====================================
-- Soft-deleted accounts are anonymized to `deleted+{id}@anonymized.local`, which
-- releases the original email for re-registration but also means a later login
-- with the original email cannot find the row to return 403.  We keep a one-way
-- hash of the original email so the login path can detect a deleted account and
-- surface the same "account not active" Forbidden response used for other
-- inactive statuses, without exposing the original address.
ALTER TABLE account ADD COLUMN IF NOT EXISTS deleted_original_email_hash TEXT;

CREATE INDEX IF NOT EXISTS idx_account_deleted_email_hash
    ON account (realm_id, deleted_original_email_hash)
    WHERE deleted_original_email_hash IS NOT NULL;
